#!/usr/bin/env python3
"""Transpose the credited DE ASCII bitmap into SuperFW's native FO layout."""
from pathlib import Path
import argparse
import struct
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
rows=(root/'assets/fonts/dssmm-ascii-rows.bin').read_bytes()
assert len(rows)==95*12
indices=[];columns=[]
for i in range(95):
    glyph=rows[i*12:(i+1)*12]
    # DE advances six pixels; tilde alone reaches column6. Give it seven to
    # retain every source pixel while keeping width/clipping bounds truthful.
    width=max(6,max((8-bit for row in glyph for bit in range(8) if row&(1<<bit)),default=0))
    assert width<=8
    indices.append(((width-1)<<13)|len(columns))
    for x in range(width):
        columns.append(sum(1<<(y+2) for y,row in enumerate(glyph) if row&(0x80>>x)))
blob=struct.pack('<2sBBI',b'FO',1,1,0)+struct.pack('<4I',32,126,2,0)
blob+=struct.pack('<'+'H'*len(indices),*indices)+struct.pack('<'+'H'*len(columns),*columns)
blob+=bytes(-len(blob)%4)
blob=blob[:4]+struct.pack('<I',len(blob))+blob[8:]
words=struct.unpack('<'+'I'*(len(blob)//4),blob)
text='''/* SPDX-License-Identifier: Apache-2.0
 * Generated by tools/generate-dssmm-font.py; do not edit.
 * DE DSSMM/EZ-FLASH ASCII bitmap, transposed from asc126_new.h.
 * See docs/FONT-PORT.md and docs/licenses/dssmm-font-apache-2.0.txt.
 */
static const uint32_t font_dssmm_ascii_embedded[] = {
'''
for i in range(0,len(words),8):text+='  '+','.join(f'0x{w:08x}'for w in words[i:i+8])+',\n'
text+='};\n'
output=root/'src/fonts/dssmm_ascii.h'
if args.check:assert output.read_text()==text,'DSSMM font header is stale'
else:output.write_text(text)
print(f'DSSMM font: {len(blob)} bytes; 95 printable ASCII glyphs.')
