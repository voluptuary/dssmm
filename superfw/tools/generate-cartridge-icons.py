#!/usr/bin/env python3
"""Generate native-style cartridge tiles without changing existing palette IDs."""
import argparse,re,struct,json,hashlib,zlib
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--preview',action='store_true');a=p.parse_args()
body=re.search(r'icons_pal\[\d+\] = \{(.*?)\};',(root/'src/res/icons.h').read_text(),re.S)[1]
palette=[int(x,16) for x in re.findall('0x[0-9a-fA-F]+',body)];native=len(palette)
previous=None
for name,label,define in [('gamegear','Game Gear cartridge','ICON_GGCART'),('pce','PC Engine HuCard','ICON_PCECARD'),('ngp','Neo Geo Pocket cartridge','ICON_NGPCART'),('ngpc','Neo Geo Pocket Color cartridge','ICON_NGPCCART'),('a26','Atari2600 cartridge','ICON_A26CART')]:
 meta=json.loads((root/f'assets/icons/{name}-source.json').read_text());raw=(root/f'assets/icons/{name}.rgb555').read_bytes();width,height=meta['dimensions']
 assert width==16 and height<=16 and len(raw)==width*height*2
 assert hashlib.sha256(raw).hexdigest()==meta['pixels_sha256']
 assert len(meta['pixel_rows'])==height and all(len(row)==width for row in meta['pixel_rows'])
 assert raw==struct.pack('<'+'H'*(width*height),*(int(meta['rgb555_palette'][c],16) for row in meta['pixel_rows'] for c in row))
 source=list(struct.unpack('<'+'H'*(width*height),raw));top=(16-height)//2;canvas=[0]*(top*16)+source+[0]*((16-height-top)*16)
 before=len(palette);pixels=[]
 for tile in range(4):
  for y in range(8):
   for x in range(8):
    value=canvas[(tile//2*8+y)*16+tile%2*8+x]
    if value and value not in palette:palette.append(value)
    pixels.append(palette.index(value) if value else 0)
 assert len(palette)<255,'Keep native selection slot255 free'
 if name!='gamegear':assert len(palette)==before,'Extra cartridges reuse the native/Game Gear palette'
 index='(sizeof(icons_img)/sizeof(icons_img[0]))' if previous is None else f'({previous}+1)'
 previous=define
 text=f'''/* SPDX-License-Identifier: GPL-3.0-or-later
 * Original DSSMM {label} icon; native SuperFW style.
 * Source/credits: assets/icons/{name}-source.json.
 * Generated by tools/generate-cartridge-icons.py; native IDs remain unchanged.
 */
#define {define} {index}
'''
 arrays=[(name+'_pixels',struct.unpack('<128H',bytes(pixels)))]
 if name=='gamegear':arrays.append(('gamegear_palette',palette[native:]))
 for symbol,values in arrays:
  text+='static const uint16_t '+symbol+'[] __attribute__((aligned(4))) = {\n'
  text+=''.join('  '+','.join(f'0x{x:04x}' for x in values[i:i+12])+',\n' for i in range(0,len(values),12))+'};\n'
 target=root/f'src/res/icon-{name}.h'
 if a.check:assert target.read_text()==text,'Regenerate cartridge icons'
 else:target.write_text(text)
 if a.preview:
  size=128;rows=[]
  for y in range(size):
   row=bytearray([0])
   for x in range(size):
    value=canvas[(y//8)*16+x//8];row.extend((((value>>s)&31)*255//31 for s in (0,5,10)));row.append(255 if value else 0)
   rows.append(row)
  def chunk(tag,data):return struct.pack('>I',len(data))+tag+data+struct.pack('>I',zlib.crc32(tag+data)&0xffffffff)
  out=root/f'build/icons/{name}.png';out.parent.mkdir(parents=True,exist_ok=True)
  out.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',size,size,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows)))+chunk(b'IEND',b''))
 print(f'{label}:256 tile bytes; {len(palette)-native} shared added palette colors.')
