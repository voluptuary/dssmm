#!/usr/bin/env python3
"""Append the DSSMM Game Gear cartridge icon without changing native sprite/palette IDs."""
import argparse,re,struct,json,hashlib
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
base=(root/'src/res/icons.h').read_text()
body=re.search(r'icons_pal\[\d+\] = \{(.*?)\};',base,re.S)[1]
palette=[int(x,16) for x in re.findall('0x[0-9a-fA-F]+',body)]
native=len(palette);raw=(root/'assets/icons/gamegear.rgb555').read_bytes();assert len(raw)==448
meta=json.loads((root/'assets/icons/gamegear-source.json').read_text())
assert hashlib.sha256(raw).hexdigest()==meta['pixels_sha256']
assert raw==struct.pack('<224H',*(int(meta['rgb555_palette'][c],16) for row in meta['pixel_rows'] for c in row))
source=list(struct.unpack('<224H',raw));canvas=[0]*16+source+[0]*16
pixels=[]
for tile in range(4):
 for y in range(8):
  for x in range(8):
   value=canvas[(tile//2*8+y)*16+tile%2*8+x]
   if value and value not in palette:palette.append(value)
   pixels.append(palette.index(value) if value else 0)
assert len(palette)<255,'Keep native selection palette slot255 free'
words=struct.unpack('<128H',bytes(pixels))
text='''/* SPDX-License-Identifier: GPL-3.0-or-later
 * Original DSSMM Game Gear cartridge icon in the native SuperFW style.
 * See assets/icons/gamegear-source.json for pixel source and credits.
 * Generated by tools/generate-gamegear-icon.py; native icons remain untouched.
 */
#define ICON_GGCART (sizeof(icons_img)/sizeof(icons_img[0]))
'''
for name,values in [('gamegear_pixels',words),('gamegear_palette',palette[native:])]:
 text+='static const uint16_t '+name+'[] __attribute__((aligned(4))) = {\n'
 text+=''.join('  '+','.join(f'0x{x:04x}'for x in values[i:i+12])+',\n' for i in range(0,len(values),12))+'};\n'
target=root/'src/res/icon-gamegear.h'
if a.check:assert target.read_text()==text,'Regenerate Game Gear icon'
else:target.write_text(text)
print(f'Game Gear icon: native-style16x14 cartridge on16x16 canvas; {len(palette)-native} added palette entries.')
