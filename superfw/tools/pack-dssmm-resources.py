#!/usr/bin/env python3
"""Append read-only background streams to the existing font asset partition.
Native font bytes/header remain identical, so font consumers keep their format.
"""
from pathlib import Path
import re,struct,argparse
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
header=(root/'src/dssmm_background_data.h').read_text()
streams=[];offsets=[];lengths=[];position=4
for theme in ('light','dark'):
 theme_offsets=[];theme_lengths=[]
 for kind in ('start','settings','horizontal','vertical','grid'):
  body=re.search(r'dssmm_'+theme+'_'+kind+r'\[\] = \{(.*?)\};',header,re.S)[1]
  words=[int(x,16) for x in re.findall(r'0x[0-9a-f]+',body)]
  stream=struct.pack('<'+'H'*len(words),*words)
  theme_offsets.append(position);theme_lengths.append(len(words));position+=len(stream);streams.append(stream)
 offsets.append(theme_offsets);lengths.append(theme_lengths)
blob=b'DBR2'+b''.join(streams);blob+=bytes(-len(blob)%4)
# The existing native icon tiles are read once for the startup VRAM upload.
# Store their exact bytes alongside other read-only resources, not in main RAM.
icon_header=(root/'src/res/icons.h').read_text()
icon_body=re.search(r'icons_img\[.*?=\s*\{(.*?)\n\};',icon_header,re.S)[1]
icon_offset=len(blob)
icon_standard=re.sub(r'#ifdef SUPPORT_NORGAMES.*?#endif','',icon_body,flags=re.S)
extras=bytearray()
for name in ['gamegear','pce','ngp','ngpc','a26']:
 header=(root/f'src/res/icon-{name}.h').read_text()
 words=re.search(name+r'_pixels\[\].*?=\s*\{(.*?)\};',header,re.S)[1]
 tile=struct.pack('<128H',*(int(x,16) for x in re.findall(r'0x[0-9a-fA-F]+',words)))
 extras.extend(tile)
icons_by_font={}
for name,body,count in [('fonts',icon_standard,16),('fonts-ext',icon_body,17)]:
 icons_by_font[name]=bytes(int(x,16) for x in re.findall(r'0x[0-9a-fA-F]+',body))
 assert len(icons_by_font[name])==count*256,'Native icon tile layout changed; review upload bounds'
 icons_by_font[name]+=extras
text='/* Generated by tools/pack-dssmm-resources.py; native font prefixes unchanged. */\n'
text+='#define DSSMM_BG_MAGIC 0x32524244u\n'
text+=f'#define DSSMM_ICON_OFFSET {icon_offset}u\n'
text+=f'#ifdef FONTS_EXT\n#define DSSMM_ICON_BYTES {len(icons_by_font["fonts-ext"])}u\n#else\n#define DSSMM_ICON_BYTES {len(icons_by_font["fonts"])}u\n#endif\n'
text+='static const uint32_t dssmm_stream_offsets[2][5] = {'+','.join('{'+','.join(map(str,row))+'}' for row in offsets)+'};\n'
text+='static const uint16_t dssmm_stream_lengths[2][5] = {'+','.join('{'+','.join(map(str,row))+'}' for row in lengths)+'};\n'
for name,define in [('fonts','STANDARD'),('fonts-ext','EXTENDED')]:
 original=(root/f'res/{name}.pack').read_bytes();offset=(len(original)+3)&~3
 assert original[:3]==b'FO\x01' and struct.unpack_from('<I',original,4)[0]==len(original),'Native font format/size changed'
 icons=icons_by_font[name]
 resources=blob+b'ICN1'+struct.pack('<I',len(icons))+icons
 resources+=bytes(-len(resources)%4)
 packed=original+bytes(offset-len(original))+resources
 assert (len(packed)+8191)//8192*8192<=0x180000,'Font/background partition overflow'
 assert packed[:len(original)]==original
 assert packed[offset:offset+4]==b'DBR2'
 out=root/f'res/{name}-dssmm.pack'
 text+=f'#define DSSMM_BG_BASE_{define} {offset}u\n'
 if args.check:assert out.read_bytes()==packed,'Stale DSSMM resource pack'
 else:out.write_bytes(packed)
 print(name,len(original),'native bytes;',len(resources),'appended bytes;',0x180000-((len(packed)+8191)//8192*8192),'reserved SDRAM bytes free')
target=root/'src/dssmm_background_offsets.h'
if args.check:assert target.read_text()==text,'Stale asset offsets'
else:target.write_text(text)
