#!/usr/bin/env python3
"""Append read-only background streams to the existing font asset partition.
Native font bytes/header remain identical, so font consumers keep their format.
"""
from pathlib import Path
import re,struct,argparse
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
header=(root/'src/dssmm_background_data.h').read_text()
streams=[]
for theme in ('light','dark'):
 body=re.search(r'dssmm_'+theme+r'_start\[\] = \{(.*?)\};',header,re.S)[1]
 words=[int(x,16) for x in re.findall(r'0x[0-9a-f]+',body)]
 streams.append(struct.pack('<'+'H'*len(words),*words))
blob=b'DBG1'+streams[0]+streams[1];blob+=bytes(-len(blob)%4)
text='/* Generated by tools/pack-dssmm-resources.py; native font prefixes unchanged. */\n'
text+=f'#define DSSMM_BG_DARK_OFFSET {4+len(streams[0])}u\n'
for name,define in [('fonts','STANDARD'),('fonts-ext','EXTENDED')]:
 original=(root/f'res/{name}.pack').read_bytes();offset=(len(original)+3)&~3
 assert original[:3]==b'FO\x01' and struct.unpack_from('<I',original,4)[0]==len(original),'Native font format/size changed'
 packed=original+bytes(offset-len(original))+blob
 assert (len(packed)+8191)//8192*8192<=0x180000,'Font/background partition overflow'
 assert packed[:len(original)]==original
 assert packed[offset:offset+4]==b'DBG1'
 out=root/f'res/{name}-dssmm.pack'
 text+=f'#define DSSMM_BG_BASE_{define} {offset}u\n'
 if args.check:assert out.read_bytes()==packed,'Stale DSSMM resource pack'
 else:out.write_bytes(packed)
 print(name,len(original),'native bytes;',len(blob),'appended bytes;',0x180000-((len(packed)+8191)//8192*8192),'reserved SDRAM bytes free')
target=root/'src/dssmm_background_offsets.h'
if args.check:assert target.read_text()==text,'Stale asset offsets'
else:target.write_text(text)
