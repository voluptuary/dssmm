#!/usr/bin/env python3
"""Reproduce lossless DS Style backgrounds with halfword run-fill tokens."""
from pathlib import Path
import struct,argparse
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
def array(name,values):
 return 'static const uint16_t '+name+'[] = {\n'+''.join('  '+','.join(f'0x{x:04x}' for x in values[i:i+12])+',\n' for i in range(0,len(values),12))+'};\n'
kinds=('start','settings','horizontal','vertical','grid','help')
text='/* SPDX-License-Identifier: Apache-2.0\n * DS Style / DSSMM DE background assets; see docs/LAUNCHER-PORT.md.\n * Generated by tools/generate-dssmm-background.py.\n */\n'
for theme in ['light','dark']:
 palette=sorted(set(value for kind in kinds for value in struct.unpack('<38400H',(root/'assets/backgrounds'/f'{theme}-{kind}.rgb555').read_bytes())))
 assert len(palette)<=16,'Background palette would collide with UI colors'
 text+=array('dssmm_'+theme+'_palette',palette+[0]*(16-len(palette)))
 for kind in kinds:
  raw=(root/'assets/backgrounds'/f'{theme}-{kind}.rgb555').read_bytes();assert len(raw)==76800
  pixels=struct.unpack('<38400H',raw);assert set(pixels)<=set(palette)
  pairs=[palette.index(pixels[i])|(palette.index(pixels[i+1])<<4) for i in range(0,38400,2)]
  tokens=[];i=0
  while i<len(pairs):
   length=1
   while length<256 and i+length<len(pairs) and pairs[i+length]==pairs[i]:length+=1
   tokens.append(((length-1)<<8)|pairs[i]);i+=length
  decoded=[]
  for token in tokens:decoded.extend([token&255]*((token>>8)+1))
  assert decoded==pairs
  text+=array('dssmm_'+theme+'_'+kind,tokens)
  print(theme,kind,len(tokens)*2,'compressed bytes; lossless 240x160')
target=root/'src/dssmm_background_data.h'
if args.check:assert target.read_text()==text,'Regenerate DSSMM backgrounds'
else:target.write_text(text)
