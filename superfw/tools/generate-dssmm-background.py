#!/usr/bin/env python3
"""Reproduce lossless DS Style backgrounds with halfword LZ tokens."""
from pathlib import Path
from collections import defaultdict,deque
import struct,argparse
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
def array(name,values):
 return 'static const uint16_t '+name+'[] = {\n'+''.join('  '+','.join(f'0x{x:04x}' for x in values[i:i+12])+',\n' for i in range(0,len(values),12))+'};\n'
text='/* SPDX-License-Identifier: Apache-2.0\n * DS Style / DSSMM DE START assets; see docs/LAUNCHER-PORT.md.\n * Generated by tools/generate-dssmm-background.py.\n */\n'
for theme in ['light','dark']:
 raw=(root/'assets/backgrounds'/f'{theme}-start.rgb555').read_bytes();assert len(raw)==76800
 pixels=struct.unpack('<38400H',raw);pal=sorted(set(pixels));assert len(pal)<=16
 pairs=[pal.index(pixels[i])|(pal.index(pixels[i+1])<<4) for i in range(0,38400,2)]
 history=defaultdict(deque);tokens=[];i=0
 while i<len(pairs):
  q=history[tuple(pairs[i:i+4])]
  while q and i-q[0]>2048:q.popleft()
  best=0;distance=0
  for prev in reversed(q):
   length=4
   while length<34 and i+length<len(pairs) and pairs[prev+length]==pairs[i+length]:length+=1
   if length>best:best=length;distance=i-prev
   if best==34:break
  if best>=4:tokens.append(((best-3)<<11)|(distance-1));end=i+best
  else:tokens.append(pairs[i]);end=i+1
  while i<end:history[tuple(pairs[i:i+4])].append(i);i+=1
 # Verify every token round-trips before writing firmware assets.
 decoded=[]
 for token in tokens:
  if token<256:decoded.append(token)
  else:
   for _ in range((token>>11)+3):decoded.append(decoded[-((token&2047)+1)])
 assert decoded==pairs
 text+=array('dssmm_'+theme+'_palette',pal+[0]*(16-len(pal)))
 text+=array('dssmm_'+theme+'_start',tokens)
 print(theme,len(tokens)*2,'compressed bytes; lossless 240x160')
target=root/'src/dssmm_background_data.h'
if args.check:assert target.read_text()==text,'Regenerate DSSMM backgrounds'
else:target.write_text(text)
