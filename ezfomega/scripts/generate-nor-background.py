#!/usr/bin/env python3
"""Generate/check the lossless NOR ROM asset; canonical BMP and RGB555 stay intact."""
import argparse
from pathlib import Path
import re
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / 'images/blank/NOR.h'
PACKED = ROOT / 'images/blank/NOR_lz.h'


def array_bytes(path, word_size):
    body = path.read_text().split('= {', 1)[-1] if '= {' in path.read_text() else path.read_text().split('=\n{', 1)[1]
    values = re.findall(r'0x[0-9a-fA-F]+', body.split('}', 1)[0])
    return b''.join(int(v, 16).to_bytes(word_size, 'little') for v in values)


def decode(data):
    assert data[0] == 0x10
    size = int.from_bytes(data[1:4], 'little')
    assert size == 240 * 160 * 2
    output = bytearray()
    pos = 4
    while len(output) < size:
        flags = data[pos]
        pos += 1
        for bit in range(7, -1, -1):
            if len(output) == size:
                break
            if flags & (1 << bit):
                a, b = data[pos:pos + 2]
                pos += 2
                length = (a >> 4) + 3
                distance = ((a & 15) << 8 | b) + 1
                assert 2 <= distance <= len(output), 'Unsafe VRAM backreference'
                assert len(output) + length <= size
                for _ in range(length):
                    output.append(output[-distance])
            else:
                output.append(data[pos])
                pos += 1
    return bytes(output)


def check():
    raw = array_bytes(RAW, 1)
    packed = array_bytes(PACKED, 4)
    assert decode(packed) == raw
    bmp = (ROOT / 'images/blank/NOR.bmp').read_bytes()
    assert struct.unpack_from('<iiHHI', bmp, 18) == (240, 160, 1, 8, 0)
    offset = struct.unpack_from('<I', bmp, 10)[0]
    pixels = bytearray()
    for y in range(159, -1, -1):
        for index in bmp[offset + y * 240:offset + (y + 1) * 240]:
            b, g, r, _ = bmp[54 + index * 4:58 + index * 4]
            pixels += struct.pack('<H', (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10))
    assert pixels == raw
    print(f'NOR asset: {len(raw)} raw -> {len(packed)} packed bytes; all pixels match BMP/header; VRAM-safe references.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate existing assets without grit')
    args = parser.parse_args()
    if not args.check:
        with tempfile.TemporaryDirectory(prefix='nor-asset-') as tmp:
            base = Path(tmp) / 'nor'
            subprocess.run(['grit', str(ROOT / 'images/blank/NOR.bmp'), '-gb', '-gB16', '-gzl', '-ftc', '-o', str(base)], check=True)
            data = array_bytes(base.with_suffix('.c'), 4)
        assert decode(data) == array_bytes(RAW, 1)
        text = '/* Generated by scripts/generate-nor-background.py; canonical assets: NOR.bmp / NOR.h. */\n'
        text += '#ifndef NOR_LZ_H\n#define NOR_LZ_H\n'
        text += f'static const unsigned int nor_background_lz[{len(data) // 4}] __attribute__((aligned(4))) = {{\n'
        words = struct.unpack(f'<{len(data) // 4}I', data)
        text += ''.join('\t' + ','.join(f'0x{v:08X}' for v in words[i:i+8]) + ',\n' for i in range(0, len(words), 8))
        PACKED.write_text(text + '};\n#endif\n')
    check()
