#!/usr/bin/env python3
"""Embed or verify this project's pinned, unmodified upstream MiGoomba payload."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('binary', nargs='?', type=Path)
    parser.add_argument('--check', action='store_true', help='Verify instead of writing')
    args = parser.parse_args()
    meta = json.loads((ROOT / 'docs/plugins/migoomba.json').read_text())
    header = ROOT / meta['embedded_header']
    if args.binary:
        data = args.binary.read_bytes()
    else:
        if not args.check:
            parser.error('Provide the upstream GBA binary, or use --check')
        text = header.read_text()
        match = re.search(r'migoomba_gba\[(\d+)\].*?=\s*\{(.*?)\};', text, re.S)
        if not match:
            raise SystemExit('Missing MiGoomba array')
        data = bytes(int(value, 16) for value in re.findall(r'0x([0-9A-Fa-f]{2})\b', match[2]))
        if len(data) != int(match[1]):
            raise SystemExit('MiGoomba declared array size mismatch')
    if len(data) != meta['bytes'] or hashlib.sha256(data).hexdigest() != meta['sha256']:
        raise SystemExit('Payload differs from this platform\'s pinned MiGoomba binary')
    if not 0xC0 <= len(data) <= 0x20000 or len(data) % 4:
        raise SystemExit('Payload must fit the 128 KiB loader cache and be word-aligned')
    if data[0xAC:0xB0] != b'GMBC' or data[0xB2] != 0x96:
        raise SystemExit('Payload is not the expected Goomba-compatible GBA image')
    if data[0xBD] != (-sum(data[0xA0:0xBD]) - 0x19) & 0xFF:
        raise SystemExit('Invalid GBA header checksum')
    rows = ['    ' + ', '.join(f'0x{byte:02X}' for byte in data[offset:offset + 16]) + ','
            for offset in range(0, len(data), 16)]
    generated = ('/* Generated by scripts/embed-migoomba.py; do not edit. */\n'
                 f'/* MiGoomba {meta["version"]}, {meta["variant"]}; upstream {meta["upstream_commit"]}. */\n'
                 '#ifndef MIGOOMBA_EMBEDDED_H\n#define MIGOOMBA_EMBEDDED_H\n\n'
                 f'const unsigned int migoomba_gba_size = {len(data)};\n'
                 f'const unsigned char migoomba_gba[{len(data)}] __attribute__((aligned(4))) = {{\n'
                 + '\n'.join(rows) + '\n};\n\n#endif\n')
    if args.check:
        if header.read_text() != generated:
            raise SystemExit('Embedded header differs from deterministic generator output')
        print(f'MiGoomba {meta["variant"]}: {len(data)} bytes, hash/header/alignment verified.')
    else:
        header.write_text(generated)


if __name__ == '__main__':
    main()
